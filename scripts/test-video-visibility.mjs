import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {transpileModule,ModuleKind,ScriptTarget} from 'typescript';
const {outputText}=transpileModule(readFileSync('src/lib/video-visibility.ts','utf8'),{compilerOptions:{module:ModuleKind.ESNext,target:ScriptTarget.ES2022}});
const {watchVideoPlayback}=await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const docEvents=new Map(),videoEvents=new Map();
globalThis.document={hidden:false,addEventListener:(n,fn)=>docEvents.set(n,fn),removeEventListener:n=>docEvents.delete(n)};
let enter,disconnected=false,plays=0,pauses=0;
globalThis.IntersectionObserver=class {constructor(fn){enter=fn;}observe(){}disconnect(){disconnected=true;}};
const video={play:()=>{plays++;return Promise.resolve();},pause:()=>pauses++,addEventListener:(n,fn)=>videoEvents.set(n,fn),removeEventListener:n=>videoEvents.delete(n)};
const stop=watchVideoPlayback(video);
assert.equal(plays,0,'offscreen videos do not start');
enter([{isIntersecting:true}]);assert.equal(plays,1,'entering viewport starts playback');
document.hidden=true;docEvents.get('visibilitychange')();assert.equal(plays,1,'background tab does not play');
document.hidden=false;docEvents.get('visibilitychange')();assert.equal(plays,2,'visible tab resumes visible video');
enter([{isIntersecting:false}]);videoEvents.get('canplay')();assert.equal(plays,2,'canplay must not restart an offscreen video');
stop();assert.ok(disconnected);assert.equal(docEvents.size,0);assert.equal(videoEvents.size,0);assert.ok(pauses>=3);
delete globalThis.IntersectionObserver;
const fallback=watchVideoPlayback(video);assert.equal(plays,3,'older browsers retain visible-tab autoplay');
fallback();delete globalThis.document;
console.log('Video tests passed: viewport entry/exit, tab changes, canplay guard, cleanup and fallback.');
